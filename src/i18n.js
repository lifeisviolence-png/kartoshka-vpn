// Older releases stored only a Russian country label; map it back so the label
// follows the interface language without forcing a subscription refresh.
const countryCodes = ['de','nl','fi','fr','us','gb','ru','ua','tr','sg','jp','kz','am','ge'];
export function countryCodeFor(label) {
  if (!label) return '';
  const value = String(label).trim().toLowerCase();
  return countryCodes.find((code) => strings.ru[`country.${code}`]?.toLowerCase() === value || strings.en[`country.${code}`]?.toLowerCase() === value) || '';
}
export function dictionaryFor(lang) { return strings[lang === 'en' ? 'en' : 'ru']; }
let language = 'ru';
export function supportedLanguages() { return ['ru', 'en']; }
export function setLanguage(next) { language = next === 'en' ? 'en' : 'ru'; return language; }
export function getLanguage() { return language; }
export function locale() { return language === 'en' ? 'en-GB' : 'ru-RU'; }
export function t(key, params = {}) {
  const table = strings[language] || strings.ru;
  const value = table[key] ?? strings.ru[key] ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? ''));
}
// Errors travel as {code, params}. Anything unfamiliar keeps its own text so a
// backend diagnostic is never swallowed.
export function errorText(error) {
  if (!error) return t('err.unknown');
  if (typeof error === 'string') return error;
  const code = String(error.code || error.message || '');
  const key = code.startsWith('err.') ? code : `err.${code}`;
  if (strings[language]?.[key] || strings.ru[key]) return t(key, error.params || {});
  return error.message || t('err.unknown');
}
