// Generates src/dns-providers.js from shared/dns-providers.json.
// The JSON is the single source: Rust embeds it with include_str!, the UI imports
// the generated module. Run after editing the JSON: node scripts/gen-dns-providers.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

export function renderModule(source) {
  const data = JSON.parse(source);
  if (!Array.isArray(data.providers) || !data.providers.length) throw new Error('dns-providers.json: providers is empty');
  for (const provider of data.providers) {
    for (const ip of provider.bootstrap || []) {
      if (!/^[0-9.]+$/.test(ip)) throw new Error(`dns-providers.json: ${provider.id} bootstrap ${ip} is not an IPv4 literal`);
    }
    for (const ip of provider.bootstrapV6 || []) {
      if (!/^[0-9a-f:]+$/i.test(ip)) throw new Error(`dns-providers.json: ${provider.id} bootstrapV6 ${ip} is not an IPv6 literal`);
    }
    if (!/^https:\/\/[0-9.]+\//.test(provider.ipUrl)) throw new Error(`dns-providers.json: ${provider.id} ipUrl must use a literal IP`);
  }
  return `// Generated by scripts/gen-dns-providers.mjs from shared/dns-providers.json.
// Do not edit by hand: change the JSON and regenerate.
export const DNS_PROVIDERS = ${JSON.stringify(data.providers, null, 2)};

export const RU_PROVIDER = DNS_PROVIDERS.find((provider) => provider.ru) || DNS_PROVIDERS[0];
export const FALLBACK_PROVIDER = DNS_PROVIDERS.find((provider) => !provider.ru) || DNS_PROVIDERS[0];
export const DNS_IP_URLS = DNS_PROVIDERS.map((provider) => provider.ipUrl);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = readFileSync(join(root, 'shared/dns-providers.json'), 'utf8');
  writeFileSync(join(root, 'src/dns-providers.js'), renderModule(source));
  console.log('src/dns-providers.js written');
}
